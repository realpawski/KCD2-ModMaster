"""Verified KCD2 XML/ZIP packaging; never treats Blender GLB as game data."""
from __future__ import annotations

import hashlib
import json
import math
import re
import xml.etree.ElementTree as ET
import zipfile
from datetime import date
from pathlib import Path, PurePosixPath

from runtime_tools import REGISTRY_VERSION, RUNTIME_VERSION


def mod_id(value: str) -> str:
    # Warhorse KM-A-57 explicitly restricts IDs to lowercase letters/underscore.
    if not re.fullmatch(r"[a-z][a-z_]{0,63}", value):
        raise ValueError("KCD2 mod IDs must contain only lowercase letters and underscores.")
    return value


def virtual_path(value: str) -> str:
    p = PurePosixPath(value.replace("\\", "/"))
    if p.is_absolute() or not p.parts or any(x in ("..", ".") for x in p.parts) or ":" in value:
        raise ValueError(f"Unsafe game data path: {value!r}")
    return str(p)


def write_manifest(target: Path, project) -> None:
    root = ET.Element("kcd_mod")
    info = ET.SubElement(root, "info")
    for key, value in (("name", project.name), ("modid", mod_id(project.id)),
                       ("description", project.description), ("author", project.author),
                       ("version", project.version), ("created_on", date.today().isoformat()),
                       ("modifies_level", "false")):
        ET.SubElement(info, key).text = str(value)
    ET.indent(root)
    target.write_bytes(ET.tostring(root, encoding="utf-8", xml_declaration=True))


def lua_literal(value) -> str:
    """Serialize data only. Lua 5.1 escapes use fixed-width decimal bytes."""
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (float, int)):
        if not math.isfinite(value):
            raise ValueError("Nonfinite registry number")
        return repr(value)
    if isinstance(value, str):
        return '"' + "".join(chr(b) if 32 <= b < 127 and b not in (34, 92)
                             else f"\\{b:03d}" for b in value.encode("utf-8")) + '"'
    if isinstance(value, list):
        return "{" + ",".join(map(lua_literal, value)) + "}"
    if isinstance(value, dict):
        return "{" + ",".join(f"[{lua_literal(k)}]={lua_literal(v)}" for k, v in sorted(value.items())) + "}"
    raise TypeError(type(value).__name__)


